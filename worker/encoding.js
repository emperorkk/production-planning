export function decodeCp1253(bytes) {
  let out = '';
  for (let i = 0; i < bytes.length; i += 8192) {
    const chunk = bytes.subarray(i, i + 8192);
    const codes = new Array(chunk.length);
    for (let j = 0; j < chunk.length; j++) {
      const b = chunk[j];
      codes[j] = b < 0x80 ? b : CP1253_HIGH[b - 0x80];
    }
    out += String.fromCharCode.apply(null, codes);
  }
  return out;
}

export function decodeSoft1(buffer, contentType = '') {
  const bytes = new Uint8Array(buffer);
  const cs = (/charset=([^;]+)/i.exec(contentType)?.[1] || '').trim().toLowerCase();
  if (cs === 'windows-1253' || cs === 'cp1253' || cs === 'iso-8859-7') return decodeCp1253(bytes);
  try {
    return new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  } catch {
    return decodeCp1253(bytes);
  }
}
